"""
Read download-provenance metadata embedded in images by the hermes
lora_dataset/lora_theme download tools (~/Documents/scripts/hermes).

Those tools write PNG tEXt chunks - "Source" (the image URL), "SourcePage"
(the gallery/thread it was found on), "Query" (the search query that
surfaced it), and "Subject" (the dataset subject/theme name) - via
PIL.PngImagePlugin.PngInfo, the same iTXt/tEXt mechanism ComfyUI uses for
its own "prompt"/"workflow" chunks, just under different key names. An
image carrying these was downloaded by that tool, not generated by
ComfyUI, so it won't have ComfyUI's "prompt" chunk - this is meant as a
fallback source of info for the same "ComfyUI Info" panel when ComfyUI's
own metadata isn't present.

Kept self-contained here (re-reading the same PNG chunks directly) rather
than importing the hermes project, since that's an unrelated, separately
versioned tool - not a shared library.
"""

_PROVENANCE_KEYS = ("Source", "SourcePage", "Query", "Subject")


def extract_source_info(image_path):
    """
    Read hermes lora_dataset/lora_theme provenance chunks from an image.

    Returns a dict with whichever of "Source", "SourcePage", "Query",
    "Subject" are present, or None if none are present (or the image can't
    be read).
    """
    try:
        from PIL import Image

        with Image.open(image_path) as img:
            info = img.info or {}
    except Exception:
        return None

    found = {key: info[key] for key in _PROVENANCE_KEYS if info.get(key)}
    return found or None
